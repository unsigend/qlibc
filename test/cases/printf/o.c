#include <limits.h>
#include <stddef.h>
#include <stdio.h>
#include <utest.h>

UTEST_CASE(o)
{
    char buf[256];
    int n;

    n = snprintf(buf, sizeof(buf), "%o", 0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%o", 1);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "1");
    n = snprintf(buf, sizeof(buf), "%o", 7);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "7");
    n = snprintf(buf, sizeof(buf), "%o", 8);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "10");
    n = snprintf(buf, sizeof(buf), "%o", 9);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "11");
    n = snprintf(buf, sizeof(buf), "%o", 10);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "12");
    n = snprintf(buf, sizeof(buf), "%o", 64);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "100");
    n = snprintf(buf, sizeof(buf), "%o", 511);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "777");
    n = snprintf(buf, sizeof(buf), "%o", 512);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "1000");
    n = snprintf(buf, sizeof(buf), "%.0o", 0);
    EXPECT_EQ_INT(n, 0);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, sizeof(buf), "%.0o", 1);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "1");
    n = snprintf(buf, sizeof(buf), "%.3o", 1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%.5o", 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00010");
    n = snprintf(buf, sizeof(buf), "%.1o", 0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%.2o", 8);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "10");
    n = snprintf(buf, sizeof(buf), "%.4o", 777);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "1411");
    n = snprintf(buf, sizeof(buf), "x%o y", 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "x10 y");
    n = snprintf(buf, sizeof(buf), "%o%o", 1, 2);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "12");
    n = snprintf(buf, sizeof(buf), "%o", 63u);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "77");
    n = snprintf(buf, 1, "%o", 8);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, 4, "%o", 64);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "100");
    n = snprintf(buf, 0, "%o", 8);
    EXPECT_EQ_INT(n, 2);
    n = snprintf(buf, sizeof(buf), "%.10o", 1);
    EXPECT_EQ_INT(n, 10);
    EXPECT_EQ_STR(buf, "0000000001");
    n = snprintf(buf, sizeof(buf), "%.2o", 100);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "144");
    n = snprintf(buf, sizeof(buf), "%o", UINT_MAX);
    if (UINT_MAX == 4294967295u) {
        EXPECT_EQ_INT(n, 11);
        EXPECT_EQ_STR(buf, "37777777777");
    }
    n = snprintf(buf, sizeof(buf), "%o", UINT_MAX - 1);
    if (UINT_MAX == 4294967295u)
        EXPECT_EQ_STR(buf, "37777777776");
    n = snprintf(buf, sizeof(buf), "%.12o", UINT_MAX);
    if (UINT_MAX == 4294967295u) {
        EXPECT_EQ_INT(n, 12);
        EXPECT_EQ_STR(buf, "037777777777");
    }
    n = snprintf(buf, sizeof(buf), "%5o", 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   10");
    n = snprintf(buf, sizeof(buf), "%-5o", 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "10   ");
    n = snprintf(buf, sizeof(buf), "%5o", 0);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "    0");
    n = snprintf(buf, sizeof(buf), "%-5o", 0);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "0    ");
    n = snprintf(buf, sizeof(buf), "%05o", 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00010");
    n = snprintf(buf, sizeof(buf), "%05o", 0);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00000");
    n = snprintf(buf, sizeof(buf), "%08o", 64);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "00000100");
    n = snprintf(buf, sizeof(buf), "%#o", 8);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "010");
    n = snprintf(buf, sizeof(buf), "%#o", 0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%#o", 64);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "0100");
    n = snprintf(buf, sizeof(buf), "%#o", 1);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "01");
    n = snprintf(buf, sizeof(buf), "%5.3o", 1);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "  001");
    n = snprintf(buf, sizeof(buf), "%8.4o", 64);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "    0100");
    n = snprintf(buf, sizeof(buf), "%*o", 5, 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   10");
    n = snprintf(buf, sizeof(buf), "%.*o", 3, 1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%*.*o", 8, 4, 64);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "    0100");
    n = snprintf(buf, sizeof(buf), "%#5o", 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "  010");
    n = snprintf(buf, sizeof(buf), "%-#5o", 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "010  ");
    n = snprintf(buf, sizeof(buf), "%#05o", 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00010");
    n = snprintf(buf, sizeof(buf), "%#*.*o", 8, 4, 64);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "    0100");
    n = snprintf(buf, sizeof(buf), "%lo", 42UL);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "52");
    n = snprintf(buf, sizeof(buf), "%llo", 42ULL);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "52");
    n = snprintf(buf, sizeof(buf), "%zo", (size_t)42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "52");
    n = snprintf(buf, sizeof(buf), "%5lo", 8UL);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   10");
    n = snprintf(buf, sizeof(buf), "%-5zo", (size_t)8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "10   ");
    n = snprintf(buf, sizeof(buf), "%.3lo", 1UL);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%08lo", 64UL);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "00000100");
    n = snprintf(buf, sizeof(buf), "%.3llo", 1ULL);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%08zo", (size_t)64);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "00000100");
    n = snprintf(buf, sizeof(buf), "%#lo", 8UL);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "010");
    n = snprintf(buf, sizeof(buf), "%#5llo", 8ULL);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "  010");
    n = snprintf(buf, sizeof(buf), "%ho", (unsigned short)42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "52");
    n = snprintf(buf, sizeof(buf), "%5ho", (unsigned short)8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   10");
    n = snprintf(buf, sizeof(buf), "%-5ho", (unsigned short)8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "10   ");
    n = snprintf(buf, sizeof(buf), "%.3ho", (unsigned short)1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%08ho", (unsigned short)64);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "00000100");
    n = snprintf(buf, sizeof(buf), "%#ho", (unsigned short)8);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "010");
    n = snprintf(buf, sizeof(buf), "%hho", (unsigned char)8);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "10");
    n = snprintf(buf, sizeof(buf), "%*o", 0, 8);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "10");
    n = snprintf(buf, sizeof(buf), "%*o", -5, 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "10   ");
    n = snprintf(buf, sizeof(buf), "%.*o", 0, 0);
    EXPECT_EQ_INT(n, 0);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, sizeof(buf), "%.*o", 0, 1);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "1");
    n = snprintf(buf, sizeof(buf), "%*.*o", 8, 0, 0);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "        ");
    n = snprintf(buf, sizeof(buf), "%#.0o", 0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%#.0o", 1);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "01");
    n = snprintf(buf, sizeof(buf), "%#8o", 8);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "     010");
    n = snprintf(buf, sizeof(buf), "%#-8o", 8);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "010     ");
    n = snprintf(buf, sizeof(buf), "%#*o", 5, 8);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "  010");
    n = snprintf(buf, sizeof(buf), "%0.5o", 1);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00001");
    n = snprintf(buf, sizeof(buf), "%0.5o", 0);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00000");
    n = snprintf(buf, sizeof(buf), "%*.*o", 6, -1, 64);
    EXPECT_EQ_INT(n, 6);
    EXPECT_EQ_STR(buf, "   100");
}
