#include <limits.h>
#include <stddef.h>
#include <stdio.h>
#include <utest.h>

UTEST_CASE(x)
{
    char buf[256];
    int n;

    n = snprintf(buf, sizeof(buf), "%x", 0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%x", 1);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "1");
    n = snprintf(buf, sizeof(buf), "%x", 9);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "9");
    n = snprintf(buf, sizeof(buf), "%x", 10);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "a");
    n = snprintf(buf, sizeof(buf), "%x", 15);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "f");
    n = snprintf(buf, sizeof(buf), "%x", 16);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "10");
    n = snprintf(buf, sizeof(buf), "%x", 255);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "ff");
    n = snprintf(buf, sizeof(buf), "%x", 256);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "100");
    n = snprintf(buf, sizeof(buf), "%X", 10);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "A");
    n = snprintf(buf, sizeof(buf), "%X", 15);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "F");
    n = snprintf(buf, sizeof(buf), "%X", 255);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "FF");
    n = snprintf(buf, sizeof(buf), "%X", 0xabc);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "ABC");
    n = snprintf(buf, sizeof(buf), "%x", 0xabc);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "abc");
    n = snprintf(buf, sizeof(buf), "%.0x", 0);
    EXPECT_EQ_INT(n, 0);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, sizeof(buf), "%.0x", 1);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "1");
    n = snprintf(buf, sizeof(buf), "%.3x", 1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%.4x", 0xff);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "00ff");
    n = snprintf(buf, sizeof(buf), "%.4X", 0xff);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "00FF");
    n = snprintf(buf, sizeof(buf), "%.1x", 0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "x%x y", 16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "x10 y");
    n = snprintf(buf, sizeof(buf), "%x%x", 1, 2);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "12");
    n = snprintf(buf, sizeof(buf), "%x", 0xdeadu);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "dead");
    n = snprintf(buf, sizeof(buf), "%X", 0xdeadu);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "DEAD");
    n = snprintf(buf, 1, "%x", 16);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, 4, "%x", 255);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "ff");
    n = snprintf(buf, 0, "%x", 16);
    EXPECT_EQ_INT(n, 2);
    n = snprintf(buf, sizeof(buf), "%.8x", 0xff);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "000000ff");
    n = snprintf(buf, sizeof(buf), "%.2x", 0x123);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "123");
    n = snprintf(buf, sizeof(buf), "%x", UINT_MAX);
    if (UINT_MAX == 4294967295u)
        EXPECT_EQ_STR(buf, "ffffffff");
    n = snprintf(buf, sizeof(buf), "%X", UINT_MAX);
    if (UINT_MAX == 4294967295u)
        EXPECT_EQ_STR(buf, "FFFFFFFF");
    n = snprintf(buf, sizeof(buf), "%.10x", UINT_MAX);
    if (UINT_MAX == 4294967295u)
        EXPECT_EQ_STR(buf, "00ffffffff");
    n = snprintf(buf, sizeof(buf), "%.10X", UINT_MAX);
    if (UINT_MAX == 4294967295u)
        EXPECT_EQ_STR(buf, "00FFFFFFFF");
    n = snprintf(buf, sizeof(buf), "%5x", 16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   10");
    n = snprintf(buf, sizeof(buf), "%-5x", 16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "10   ");
    n = snprintf(buf, sizeof(buf), "%5X", 255);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   FF");
    n = snprintf(buf, sizeof(buf), "%-5X", 255);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "FF   ");
    n = snprintf(buf, sizeof(buf), "%05x", 16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00010");
    n = snprintf(buf, sizeof(buf), "%05X", 255);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "000FF");
    n = snprintf(buf, sizeof(buf), "%08x", 0xff);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "000000ff");
    n = snprintf(buf, sizeof(buf), "%#x", 255);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "0xff");
    n = snprintf(buf, sizeof(buf), "%#x", 0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%#08x", 0);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "00000000");
    n = snprintf(buf, sizeof(buf), "%#x", 0xabc);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "0xabc");
    n = snprintf(buf, sizeof(buf), "%#X", 255);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "0XFF");
    n = snprintf(buf, sizeof(buf), "%#X", 0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%#X", 0xabc);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "0XABC");
    n = snprintf(buf, sizeof(buf), "%5.3x", 1);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "  001");
    n = snprintf(buf, sizeof(buf), "%8.4x", 0xff);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "    00ff");
    n = snprintf(buf, sizeof(buf), "%*x", 5, 16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   10");
    n = snprintf(buf, sizeof(buf), "%.*x", 3, 1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%*.*x", 8, 4, 0xff);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "    00ff");
    n = snprintf(buf, sizeof(buf), "%#5x", 16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, " 0x10");
    n = snprintf(buf, sizeof(buf), "%-#5x", 16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "0x10 ");
    n = snprintf(buf, sizeof(buf), "%#05x", 16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "0x010");
    n = snprintf(buf, sizeof(buf), "%#*.*x", 8, 4, 0xff);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "  0x00ff");
    n = snprintf(buf, sizeof(buf), "%lx", 0xffUL);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "ff");
    n = snprintf(buf, sizeof(buf), "%llx", 0xffULL);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "ff");
    n = snprintf(buf, sizeof(buf), "%llx", ULLONG_MAX);
    if (ULLONG_MAX == 18446744073709551615ULL)
        EXPECT_EQ_STR(buf, "ffffffffffffffff");
    n = snprintf(buf, sizeof(buf), "%zx", (size_t)0xff);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "ff");
    n = snprintf(buf, sizeof(buf), "%lX", 0xabcUL);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "ABC");
    n = snprintf(buf, sizeof(buf), "%llX", 0xabcULL);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "ABC");
    n = snprintf(buf, sizeof(buf), "%zX", (size_t)0xabc);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "ABC");
    n = snprintf(buf, sizeof(buf), "%5lx", 16UL);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   10");
    n = snprintf(buf, sizeof(buf), "%-5zx", (size_t)16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "10   ");
    n = snprintf(buf, sizeof(buf), "%.3lx", 1UL);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%08lx", 0xffUL);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "000000ff");
    n = snprintf(buf, sizeof(buf), "%.3llx", 1ULL);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%08zx", (size_t)0xff);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "000000ff");
    n = snprintf(buf, sizeof(buf), "%#lx", 255UL);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "0xff");
    n = snprintf(buf, sizeof(buf), "%#5llX", 16ULL);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, " 0X10");
    n = snprintf(buf, sizeof(buf), "%hx", (unsigned short)0xff);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "ff");
    n = snprintf(buf, sizeof(buf), "%hX", (unsigned short)0xabc);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "ABC");
    n = snprintf(buf, sizeof(buf), "%5hx", (unsigned short)16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   10");
    n = snprintf(buf, sizeof(buf), "%-5hx", (unsigned short)16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "10   ");
    n = snprintf(buf, sizeof(buf), "%.3hx", (unsigned short)1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%08hx", (unsigned short)0xff);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "000000ff");
    n = snprintf(buf, sizeof(buf), "%#hx", (unsigned short)255);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "0xff");
    n = snprintf(buf, sizeof(buf), "%hhx", (unsigned char)0xff);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "ff");
    n = snprintf(buf, sizeof(buf), "%*x", 0, 16);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "10");
    n = snprintf(buf, sizeof(buf), "%*x", -5, 16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "10   ");
    n = snprintf(buf, sizeof(buf), "%.*x", 0, 0);
    EXPECT_EQ_INT(n, 0);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, sizeof(buf), "%.*x", 0, 1);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "1");
    n = snprintf(buf, sizeof(buf), "%*.*x", 8, 0, 0);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "        ");
    n = snprintf(buf, sizeof(buf), "%#.0x", 0);
    EXPECT_EQ_INT(n, 0);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, sizeof(buf), "%#.0x", 1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "0x1");
    n = snprintf(buf, sizeof(buf), "%#.0X", 1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "0X1");
    n = snprintf(buf, sizeof(buf), "%#8x", 16);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "    0x10");
    n = snprintf(buf, sizeof(buf), "%#-8x", 16);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "0x10    ");
    n = snprintf(buf, sizeof(buf), "%#8X", 255);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "    0XFF");
    n = snprintf(buf, sizeof(buf), "%#*x", 5, 16);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, " 0x10");
    n = snprintf(buf, sizeof(buf), "%0.5x", 1);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00001");
    n = snprintf(buf, sizeof(buf), "%0.5x", 0);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00000");
    n = snprintf(buf, sizeof(buf), "%*.*x", 6, -1, 0xff);
    EXPECT_EQ_INT(n, 6);
    EXPECT_EQ_STR(buf, "    ff");
    n = snprintf(buf, sizeof(buf), "%1x", 0x123);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "123");
    n = snprintf(buf, sizeof(buf), "%-1x", 0x123);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "123");
    n = snprintf(buf, sizeof(buf), "%zx", (size_t)0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
}
