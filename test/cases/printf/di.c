#include <limits.h>
#include <stddef.h>
#include <stdio.h>
#include <utest.h>

UTEST_CASE(di)
{
    char buf[256];
    int n;

    n = snprintf(buf, sizeof(buf), "%d", 0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%d", 1);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "1");
    n = snprintf(buf, sizeof(buf), "%d", -1);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "-1");
    n = snprintf(buf, sizeof(buf), "%d", 42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "42");
    n = snprintf(buf, sizeof(buf), "%d", -42);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "-42");
    n = snprintf(buf, sizeof(buf), "%i", 42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "42");
    n = snprintf(buf, sizeof(buf), "%i", -42);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "-42");
    n = snprintf(buf, sizeof(buf), "%.3d", 1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%.5d", 42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00042");
    n = snprintf(buf, sizeof(buf), "%.1d", 0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%.0d", 0);
    EXPECT_EQ_INT(n, 0);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, sizeof(buf), "%.3d", -1);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "-001");
    n = snprintf(buf, sizeof(buf), "%.2d", 7);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "07");
    n = snprintf(buf, sizeof(buf), "x%d y", 42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "x42 y");
    n = snprintf(buf, sizeof(buf), "%d%d", 1, 2);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "12");
    n = snprintf(buf, sizeof(buf), "%d", 12345);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "12345");
    n = snprintf(buf, sizeof(buf), "%d", -12345);
    EXPECT_EQ_INT(n, 6);
    EXPECT_EQ_STR(buf, "-12345");
    n = snprintf(buf, sizeof(buf), "%.6d", 123);
    EXPECT_EQ_INT(n, 6);
    EXPECT_EQ_STR(buf, "000123");
    n = snprintf(buf, sizeof(buf), "%.4d", -99);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "-0099");
    n = snprintf(buf, 1, "%d", 42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, 3, "%d", 42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "42");
    n = snprintf(buf, 0, "%d", 42);
    EXPECT_EQ_INT(n, 2);
    n = snprintf(buf, sizeof(buf), "%.0d", 1);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "1");
    n = snprintf(buf, sizeof(buf), "%.0i", 0);
    EXPECT_EQ_INT(n, 0);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, sizeof(buf), "%d", 9);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "9");
    n = snprintf(buf, sizeof(buf), "%d", 10);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "10");
    n = snprintf(buf, sizeof(buf), "%d", 99);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "99");
    n = snprintf(buf, sizeof(buf), "%d", 100);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "100");
    n = snprintf(buf, sizeof(buf), "%d", -9);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "-9");
    n = snprintf(buf, sizeof(buf), "%d", -100);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "-100");
    n = snprintf(buf, sizeof(buf), "%.2d", 123);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "123");
    n = snprintf(buf, sizeof(buf), "%.10d", 1);
    EXPECT_EQ_INT(n, 10);
    EXPECT_EQ_STR(buf, "0000000001");
    n = snprintf(buf, sizeof(buf), "%.4d", 99999);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "99999");
    n = snprintf(buf, sizeof(buf), "%d %d", 0, -1);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "0 -1");
    n = snprintf(buf, sizeof(buf), "%d %i", 42, 42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "42 42");
    n = snprintf(buf, sizeof(buf), "%dxy", 12);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "12xy");
    n = snprintf(buf, sizeof(buf), "xy%d", 12);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "xy12");
    n = snprintf(buf, 2, "%d", 9);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "9");
    n = snprintf(buf, 4, "%d", -1);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "-1");
    n = snprintf(buf, 2, "%.3d", 1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%d", 999999);
    EXPECT_EQ_INT(n, 6);
    EXPECT_EQ_STR(buf, "999999");
    n = snprintf(buf, sizeof(buf), "%d", -999999);
    EXPECT_EQ_INT(n, 7);
    EXPECT_EQ_STR(buf, "-999999");
    n = snprintf(buf, sizeof(buf), "%.1d", 5);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "5");
    n = snprintf(buf, sizeof(buf), "%.0d", 7);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "7");

    n = snprintf(buf, sizeof(buf), "%d", INT_MAX);
    EXPECT_GT_INT(n, 0);
    if (INT_MAX == 2147483647) {
        EXPECT_EQ_INT(n, 10);
        EXPECT_EQ_STR(buf, "2147483647");
    }
    n = snprintf(buf, sizeof(buf), "%d", INT_MIN);
    EXPECT_GT_INT(n, 0);
    if (INT_MIN == (-2147483647 - 1)) {
        EXPECT_EQ_INT(n, 11);
        EXPECT_EQ_STR(buf, "-2147483648");
    }
    n = snprintf(buf, sizeof(buf), "%i", INT_MAX);
    if (INT_MAX == 2147483647)
        EXPECT_EQ_STR(buf, "2147483647");
    n = snprintf(buf, sizeof(buf), "%i", INT_MIN);
    if (INT_MIN == (-2147483647 - 1))
        EXPECT_EQ_STR(buf, "-2147483648");
    n = snprintf(buf, sizeof(buf), "%.12d", INT_MAX);
    if (INT_MAX == 2147483647) {
        EXPECT_EQ_INT(n, 12);
        EXPECT_EQ_STR(buf, "002147483647");
    }
    n = snprintf(buf, sizeof(buf), "%.12d", INT_MIN);
    if (INT_MIN == (-2147483647 - 1)) {
        EXPECT_EQ_INT(n, 13);
        EXPECT_EQ_STR(buf, "-002147483648");
    }

    n = snprintf(buf, sizeof(buf), "%5d", 42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   42");
    n = snprintf(buf, sizeof(buf), "%-5d", 42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "42   ");
    n = snprintf(buf, sizeof(buf), "%5d", -42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "  -42");
    n = snprintf(buf, sizeof(buf), "%-5d", -42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "-42  ");
    n = snprintf(buf, sizeof(buf), "%3d", 1234);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "1234");
    n = snprintf(buf, sizeof(buf), "%5i", 1);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "    1");
    n = snprintf(buf, sizeof(buf), "%-5i", 1);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "1    ");
    n = snprintf(buf, sizeof(buf), "%05d", 42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00042");
    n = snprintf(buf, sizeof(buf), "%05d", -42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "-0042");
    n = snprintf(buf, sizeof(buf), "%05i", 1);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00001");
    n = snprintf(buf, sizeof(buf), "%08d", 123);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "00000123");
    n = snprintf(buf, sizeof(buf), "%5.3d", 1);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "  001");
    n = snprintf(buf, sizeof(buf), "%8.4d", 42);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "    0042");
    n = snprintf(buf, sizeof(buf), "%-5.3d", 1);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "001  ");
    n = snprintf(buf, sizeof(buf), "%*d", 5, 42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   42");
    n = snprintf(buf, sizeof(buf), "%*d", -5, 42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "42   ");
    n = snprintf(buf, sizeof(buf), "%-05d", 42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "42   ");
    n = snprintf(buf, sizeof(buf), "%.*d", 3, 1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%*.*d", 8, 4, 42);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "    0042");
    n = snprintf(buf, sizeof(buf), "%*.*i", 6, 2, 7);
    EXPECT_EQ_INT(n, 6);
    EXPECT_EQ_STR(buf, "    07");
    n = snprintf(buf, sizeof(buf), "%-*.*d", 8, 4, 42);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "0042    ");
    n = snprintf(buf, sizeof(buf), "%ld", 42L);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "42");
    n = snprintf(buf, sizeof(buf), "%ld", -123L);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "-123");
    n = snprintf(buf, sizeof(buf), "%lld", 42LL);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "42");
    n = snprintf(buf, sizeof(buf), "%lld", -123LL);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "-123");
    n = snprintf(buf, sizeof(buf), "%lld", LLONG_MAX);
    if (LLONG_MAX == 9223372036854775807LL) {
        EXPECT_EQ_INT(n, 19);
        EXPECT_EQ_STR(buf, "9223372036854775807");
    }
    n = snprintf(buf, sizeof(buf), "%lld", LLONG_MIN);
    if (LLONG_MIN == (-9223372036854775807LL - 1)) {
        EXPECT_EQ_INT(n, 20);
        EXPECT_EQ_STR(buf, "-9223372036854775808");
    }
    n = snprintf(buf, sizeof(buf), "%zd", (ptrdiff_t)42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "42");
    n = snprintf(buf, sizeof(buf), "%zd", (ptrdiff_t)-123);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "-123");
    n = snprintf(buf, sizeof(buf), "%li", 99L);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "99");
    n = snprintf(buf, sizeof(buf), "%5ld", 42L);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   42");
    n = snprintf(buf, sizeof(buf), "%-5ld", 42L);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "42   ");
    n = snprintf(buf, sizeof(buf), "%.3ld", 1L);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%08ld", 123L);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "00000123");
    n = snprintf(buf, sizeof(buf), "%.3lld", 1LL);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%08zd", (ptrdiff_t)123);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "00000123");
    n = snprintf(buf, sizeof(buf), "%hd", (short)42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "42");
    n = snprintf(buf, sizeof(buf), "%hd", (short)-123);
    EXPECT_EQ_INT(n, 4);
    EXPECT_EQ_STR(buf, "-123");
    n = snprintf(buf, sizeof(buf), "%hi", (short)99);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "99");
    n = snprintf(buf, sizeof(buf), "%5hd", (short)42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "   42");
    n = snprintf(buf, sizeof(buf), "%-5hd", (short)42);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "42   ");
    n = snprintf(buf, sizeof(buf), "%.3hd", (short)1);
    EXPECT_EQ_INT(n, 3);
    EXPECT_EQ_STR(buf, "001");
    n = snprintf(buf, sizeof(buf), "%08hd", (short)123);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "00000123");
    n = snprintf(buf, sizeof(buf), "%hhd", (signed char)-1);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "-1");
    n = snprintf(buf, sizeof(buf), "%hhd", (signed char)42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "42");
    n = snprintf(buf, sizeof(buf), "%*d", 0, 42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "42");
    n = snprintf(buf, sizeof(buf), "%*d", 1, 42);
    EXPECT_EQ_INT(n, 2);
    EXPECT_EQ_STR(buf, "42");
    n = snprintf(buf, sizeof(buf), "%.*d", 0, 0);
    EXPECT_EQ_INT(n, 0);
    EXPECT_EQ_STR(buf, "");
    n = snprintf(buf, sizeof(buf), "%.*d", 0, 5);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "5");
    n = snprintf(buf, sizeof(buf), "%*.*d", 10, 0, 0);
    EXPECT_EQ_INT(n, 10);
    EXPECT_EQ_STR(buf, "          ");
    n = snprintf(buf, sizeof(buf), "%ld", 1234567890L);
    EXPECT_EQ_INT(n, 10);
    EXPECT_EQ_STR(buf, "1234567890");
    n = snprintf(buf, sizeof(buf), "%ld", -1234567890L);
    EXPECT_EQ_INT(n, 11);
    EXPECT_EQ_STR(buf, "-1234567890");
    n = snprintf(buf, sizeof(buf), "%010d", 42);
    EXPECT_EQ_INT(n, 10);
    EXPECT_EQ_STR(buf, "0000000042");
    n = snprintf(buf, sizeof(buf), "%010d", -42);
    EXPECT_EQ_INT(n, 10);
    EXPECT_EQ_STR(buf, "-000000042");
    n = snprintf(buf, sizeof(buf), "%0.5d", 1);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00001");
    n = snprintf(buf, sizeof(buf), "%0.5d", 0);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00000");
    n = snprintf(buf, sizeof(buf), "%0.5i", 123);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "00123");
    n = snprintf(buf, sizeof(buf), "%*.*d", 5, 0, 0);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "     ");
    n = snprintf(buf, sizeof(buf), "%-*.*d", 5, 0, 0);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "     ");
    n = snprintf(buf, sizeof(buf), "%*d", -8, 123);
    EXPECT_EQ_INT(n, 8);
    EXPECT_EQ_STR(buf, "123     ");
    n = snprintf(buf, sizeof(buf), "%*.*d", 6, -1, 42);
    EXPECT_EQ_INT(n, 6);
    EXPECT_EQ_STR(buf, "    42");
    n = snprintf(buf, sizeof(buf), "%hd", SHRT_MAX);
    if (SHRT_MAX == 32767) {
        EXPECT_EQ_INT(n, 5);
        EXPECT_EQ_STR(buf, "32767");
    }
    n = snprintf(buf, sizeof(buf), "%hd", SHRT_MIN);
    if (SHRT_MIN == -32768) {
        EXPECT_EQ_INT(n, 6);
        EXPECT_EQ_STR(buf, "-32768");
    }
    n = snprintf(buf, sizeof(buf), "%lli", 0LL);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%zd", (ptrdiff_t)0);
    EXPECT_EQ_INT(n, 1);
    EXPECT_EQ_STR(buf, "0");
    n = snprintf(buf, sizeof(buf), "%1d", 12345);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "12345");
    n = snprintf(buf, sizeof(buf), "%-1d", 12345);
    EXPECT_EQ_INT(n, 5);
    EXPECT_EQ_STR(buf, "12345");
}
