#include <string.h>
#include <utest.h>

UTEST_CASE(strstr)
{
    char one[32];

    EXPECT_NULL(strstr("abcd", "z"));
    EXPECT_NULL(strstr("abcd", "abx"));
    strcpy(one, "abcd");
    EXPECT_EQ_PTR(strstr(one, "c"), one + 2);
    EXPECT_EQ_PTR(strstr(one, "bc"), one + 1);
    EXPECT_EQ_PTR(strstr(one, "d"), one + 3);
    EXPECT_EQ_PTR(strstr(one, "cd"), one + 2);
    EXPECT_EQ_PTR(strstr(one, "abc"), one);
    EXPECT_EQ_PTR(strstr(one, "abcd"), one);
    EXPECT_NULL(strstr(one, "abcde"));
    EXPECT_NULL(strstr(one, "de"));
    EXPECT_EQ_PTR(strstr(one, ""), one);
    strcpy(one, "ababa");
    EXPECT_EQ_PTR(strstr(one, "ba"), one + 1);
    strcpy(one, "");
    EXPECT_NULL(strstr(one, "b"));
    EXPECT_EQ_PTR(strstr(one, ""), one);
    strcpy(one, "bcbca");
    EXPECT_EQ_PTR(strstr(one, "bca"), one + 2);
    strcpy(one, "bbbcabbca");
    EXPECT_EQ_PTR(strstr(one, "bbca"), one + 1);
    strcpy(one, "hello");
    EXPECT_EQ_PTR(strstr(one, "hello"), one);
    EXPECT_EQ_PTR(strstr(one, "hell"), one);
    EXPECT_EQ_PTR(strstr(one, "ello"), one + 1);
    EXPECT_EQ_PTR(strstr(one, "ell"), one + 1);
    EXPECT_EQ_PTR(strstr(one, "lo"), one + 3);
    EXPECT_EQ_PTR(strstr(one, "h"), one);
    EXPECT_EQ_PTR(strstr(one, "e"), one + 1);
    EXPECT_EQ_PTR(strstr(one, "l"), one + 2);
    EXPECT_EQ_PTR(strstr(one, "o"), one + 4);
    EXPECT_EQ_PTR(strstr(one, ""), one);
    EXPECT_NULL(strstr(one, "world"));
    EXPECT_NULL(strstr(one, "x"));
    EXPECT_NULL(strstr(one, "xyz"));
    strcpy(one, "a");
    EXPECT_EQ_PTR(strstr(one, ""), one);
    EXPECT_EQ_PTR(strstr(one, "a"), one);
    EXPECT_NULL(strstr(one, "b"));
    strcpy(one, "abc");
    EXPECT_EQ_PTR(strstr(one, "abc"), one);
    EXPECT_EQ_PTR(strstr(one, "ab"), one);
    EXPECT_EQ_PTR(strstr(one, "bc"), one + 1);
    EXPECT_EQ_PTR(strstr(one, "a"), one);
    EXPECT_EQ_PTR(strstr(one, "b"), one + 1);
    EXPECT_EQ_PTR(strstr(one, "c"), one + 2);
    EXPECT_NULL(strstr(one, "d"));
    strcpy(one, "Hello World");
    EXPECT_EQ_PTR(strstr(one, "Hello"), one);
    EXPECT_EQ_PTR(strstr(one, "World"), one + 6);
    EXPECT_EQ_PTR(strstr(one, " "), one + 5);
    EXPECT_EQ_PTR(strstr(one, "lo"), one + 3);
    EXPECT_EQ_PTR(strstr(one, "Wor"), one + 6);
    EXPECT_NULL(strstr(one, "hello"));
    EXPECT_NULL(strstr(one, "world"));
    strcpy(one, "aabbcc");
    EXPECT_EQ_PTR(strstr(one, "aa"), one);
    EXPECT_EQ_PTR(strstr(one, "bb"), one + 2);
    EXPECT_EQ_PTR(strstr(one, "cc"), one + 4);
    strcpy(one, "test");
    EXPECT_EQ_PTR(strstr(one, "test"), one);
    EXPECT_EQ_PTR(strstr(one, "tes"), one);
    EXPECT_EQ_PTR(strstr(one, "est"), one + 1);
    EXPECT_EQ_PTR(strstr(one, "st"), one + 2);
    EXPECT_EQ_PTR(strstr(one, "t"), one);
    strcpy(one, "testtest");
    EXPECT_EQ_PTR(strstr(one, "test"), one);
    strcpy(one, "prefixsuffix");
    EXPECT_EQ_PTR(strstr(one, "prefix"), one);
    EXPECT_EQ_PTR(strstr(one, "suffix"), one + 6);
    EXPECT_EQ_PTR(strstr(one, "fix"), one + 3);
    strcpy(one, "12345");
    EXPECT_EQ_PTR(strstr(one, "123"), one);
    EXPECT_EQ_PTR(strstr(one, "234"), one + 1);
    EXPECT_EQ_PTR(strstr(one, "345"), one + 2);
    EXPECT_EQ_PTR(strstr(one, "45"), one + 3);
    EXPECT_NULL(strstr(one, "678"));
    strcpy(one, "xxxxx");
    EXPECT_EQ_PTR(strstr(one, "xx"), one);
    EXPECT_EQ_PTR(strstr(one, "xxx"), one);
    strcpy(one, "ababab");
    EXPECT_EQ_PTR(strstr(one, "ab"), one);
    EXPECT_EQ_PTR(strstr(one, "ba"), one + 1);
    strcpy(one, "mississippi");
    EXPECT_EQ_PTR(strstr(one, "issi"), one + 1);
    EXPECT_EQ_PTR(strstr(one, "ssippi"), one + 5);
    EXPECT_NULL(strstr(one, "mississippis"));
    strcpy(one, "a\203bc");
    EXPECT_EQ_PTR(strstr(one, "\203b"), one + 1);
    EXPECT_NULL(strstr(one, "\204"));
}
