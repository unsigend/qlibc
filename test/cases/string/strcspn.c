#include <string.h>
#include <utest.h>

UTEST_CASE(strcspn)
{
    EXPECT_EQ_UINT(strcspn("", ""), 0);
    EXPECT_EQ_UINT(strcspn("", "abc"), 0);
    EXPECT_EQ_UINT(strcspn("abc", ""), 3);
    EXPECT_EQ_UINT(strcspn("abc", "abc"), 0);
    EXPECT_EQ_UINT(strcspn("abcba", "qx"), 5);
    EXPECT_EQ_UINT(strcspn("abcba", "cx"), 2);
    EXPECT_EQ_UINT(strcspn("abc", "a"), 0);
    EXPECT_EQ_UINT(strcspn("abc", "b"), 1);
    EXPECT_EQ_UINT(strcspn("abc", "c"), 2);
    EXPECT_EQ_UINT(strcspn("abc", "ab"), 0);
    EXPECT_EQ_UINT(strcspn("abc", "ac"), 0);
    EXPECT_EQ_UINT(strcspn("abc", "bc"), 1);
    EXPECT_EQ_UINT(strcspn("hello", "helo"), 0);
    EXPECT_EQ_UINT(strcspn("hello", "h"), 0);
    EXPECT_EQ_UINT(strcspn("hello", "e"), 1);
    EXPECT_EQ_UINT(strcspn("hello", "l"), 2);
    EXPECT_EQ_UINT(strcspn("hello", "o"), 4);
    EXPECT_EQ_UINT(strcspn("hello", "xyz"), 5);
    EXPECT_EQ_UINT(strcspn("hello", " "), 5);
    EXPECT_EQ_UINT(strcspn("hello world", " "), 5);
    EXPECT_EQ_UINT(strcspn("hello world", "w"), 6);
    EXPECT_EQ_UINT(strcspn("hello,world", ","), 5);
    EXPECT_EQ_UINT(strcspn("hello,world", ",."), 5);
    EXPECT_EQ_UINT(strcspn("path/to/file", "/"), 4);
    EXPECT_EQ_UINT(strcspn("path/to/file", "/\\"), 4);
    EXPECT_EQ_UINT(strcspn("12345", "1"), 0);
    EXPECT_EQ_UINT(strcspn("12345", "5"), 4);
    EXPECT_EQ_UINT(strcspn("12345", "6"), 5);
    EXPECT_EQ_UINT(strcspn("abc123", "123"), 3);
    EXPECT_EQ_UINT(strcspn("abc123", "abc"), 0);
    EXPECT_EQ_UINT(strcspn("123abc", "abc"), 3);
    EXPECT_EQ_UINT(strcspn("123abc", "123"), 0);
    EXPECT_EQ_UINT(strcspn("aaa", "a"), 0);
    EXPECT_EQ_UINT(strcspn("aaa", "b"), 3);
    EXPECT_EQ_UINT(strcspn("aabbcc", "a"), 0);
    EXPECT_EQ_UINT(strcspn("aabbcc", "b"), 2);
    EXPECT_EQ_UINT(strcspn("aabbcc", "c"), 4);
    EXPECT_EQ_UINT(strcspn("aabbcc", "d"), 6);
    EXPECT_EQ_UINT(strcspn("   hello", "h"), 3);
    EXPECT_EQ_UINT(strcspn("   hello", " "), 0);
    EXPECT_EQ_UINT(strcspn("   hello", "helo"), 3);
    EXPECT_EQ_UINT(strcspn("\t\n\vhello", "h"), 3);
    EXPECT_EQ_UINT(strcspn("\t\n\vhello", "\t\n\v"), 0);
    EXPECT_EQ_UINT(strcspn("   \t\n  ", "a"), 7);
    EXPECT_EQ_UINT(strcspn("   \t\n  ", " "), 0);
    EXPECT_EQ_UINT(strcspn("   \t\n  ", "\t"), 3);
    EXPECT_EQ_UINT(strcspn("   \t\n  ", "\n"), 4);
    EXPECT_EQ_UINT(strcspn("test", "t"), 0);
    EXPECT_EQ_UINT(strcspn("test", "e"), 1);
    EXPECT_EQ_UINT(strcspn("test", "s"), 2);
    EXPECT_EQ_UINT(strcspn("test", "x"), 4);
    EXPECT_EQ_UINT(strcspn("prefixsuffix", "s"), 6);
    EXPECT_EQ_UINT(strcspn("prefixsuffix", "pre"), 0);
    EXPECT_EQ_UINT(strcspn("prefixsuffix", "fix"), 3);
    EXPECT_EQ_UINT(strcspn("ABC", "A"), 0);
    EXPECT_EQ_UINT(strcspn("ABC", "B"), 1);
    EXPECT_EQ_UINT(strcspn("ABC", "C"), 2);
    EXPECT_EQ_UINT(strcspn("ABC", "BC"), 1);
    EXPECT_EQ_UINT(strcspn("ABC", "D"), 3);
    EXPECT_EQ_UINT(strcspn("0123456789", "0"), 0);
    EXPECT_EQ_UINT(strcspn("0123456789", "5"), 5);
    EXPECT_EQ_UINT(strcspn("0123456789", "9"), 9);
    EXPECT_EQ_UINT(strcspn("0123456789", "a"), 10);
    EXPECT_EQ_UINT(strcspn("abcdefghijklmnopqrstuvwxyz", "a"), 0);
    EXPECT_EQ_UINT(strcspn("abcdefghijklmnopqrstuvwxyz", "z"), 25);
    EXPECT_EQ_UINT(strcspn("abcdefghijklmnopqrstuvwxyz", "m"), 12);
    EXPECT_EQ_UINT(strcspn("abcdefghijklmnopqrstuvwxyz", "0123456789"), 26);
    EXPECT_EQ_UINT(strcspn("test123", "0123456789"), 4);
    EXPECT_EQ_UINT(strcspn("123test", "0123456789"), 0);
    EXPECT_EQ_UINT(strcspn("test", "0123456789"), 4);
    EXPECT_EQ_UINT(strcspn("111222333", "2"), 3);
    EXPECT_EQ_UINT(strcspn("111222333", "3"), 6);
    EXPECT_EQ_UINT(strcspn("111222333", "4"), 9);
    EXPECT_EQ_UINT(strcspn("ABCDEF", "F"), 5);
    EXPECT_EQ_UINT(strcspn("ABCDEF", "DEF"), 3);
    EXPECT_EQ_UINT(strcspn("a\203b", "\203"), 1);
    EXPECT_EQ_UINT(strcspn("a\203b", "b"), 2);
    EXPECT_EQ_UINT(strcspn("\203abc", "abc"), 1);
}
