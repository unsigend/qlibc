#include <string.h>
#include <utest.h>

UTEST_CASE(strpbrk)
{
    char one[32];

    EXPECT_NULL(strpbrk("abcd", "z"));
    strcpy(one, "abcd");
    EXPECT_EQ_PTR(strpbrk(one, "c"), one + 2);
    EXPECT_EQ_PTR(strpbrk(one, "d"), one + 3);
    EXPECT_EQ_PTR(strpbrk(one, "a"), one);
    EXPECT_NULL(strpbrk(one, ""));
    EXPECT_EQ_PTR(strpbrk(one, "cb"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "ac"), one);
    strcpy(one, "abcabdea");
    EXPECT_EQ_PTR(strpbrk(one, "b"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "cb"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "db"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "efgh"), one + 6);
    strcpy(one, "");
    EXPECT_NULL(strpbrk(one, "bc"));
    EXPECT_NULL(strpbrk(one, ""));
    strcpy(one, "hello");
    EXPECT_EQ_PTR(strpbrk(one, "h"), one);
    EXPECT_EQ_PTR(strpbrk(one, "e"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "l"), one + 2);
    EXPECT_EQ_PTR(strpbrk(one, "o"), one + 4);
    EXPECT_EQ_PTR(strpbrk(one, "helo"), one);
    EXPECT_NULL(strpbrk(one, "xyz"));
    EXPECT_NULL(strpbrk(one, "ABC"));
    strcpy(one, "a");
    EXPECT_EQ_PTR(strpbrk(one, "a"), one);
    EXPECT_EQ_PTR(strpbrk(one, "ab"), one);
    EXPECT_NULL(strpbrk(one, "b"));
    strcpy(one, "abc");
    EXPECT_EQ_PTR(strpbrk(one, "a"), one);
    EXPECT_EQ_PTR(strpbrk(one, "b"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "c"), one + 2);
    EXPECT_EQ_PTR(strpbrk(one, "ab"), one);
    EXPECT_EQ_PTR(strpbrk(one, "bc"), one + 1);
    strcpy(one, "12345");
    EXPECT_EQ_PTR(strpbrk(one, "54321"), one);
    EXPECT_EQ_PTR(strpbrk(one, "5"), one + 4);
    EXPECT_NULL(strpbrk(one, "a"));
    strcpy(one, "abc123");
    EXPECT_EQ_PTR(strpbrk(one, "123"), one + 3);
    EXPECT_EQ_PTR(strpbrk(one, "abc"), one);
    strcpy(one, "123abc");
    EXPECT_EQ_PTR(strpbrk(one, "abc"), one + 3);
    EXPECT_EQ_PTR(strpbrk(one, "123"), one);
    strcpy(one, "aaa");
    EXPECT_EQ_PTR(strpbrk(one, "a"), one);
    EXPECT_NULL(strpbrk(one, "b"));
    strcpy(one, "aabbcc");
    EXPECT_EQ_PTR(strpbrk(one, "a"), one);
    EXPECT_EQ_PTR(strpbrk(one, "b"), one + 2);
    EXPECT_EQ_PTR(strpbrk(one, "c"), one + 4);
    EXPECT_NULL(strpbrk(one, "d"));
    strcpy(one, "   hello");
    EXPECT_EQ_PTR(strpbrk(one, " "), one);
    EXPECT_EQ_PTR(strpbrk(one, "h"), one + 3);
    EXPECT_EQ_PTR(strpbrk(one, "helo"), one + 3);
    strcpy(one, "\t\n\vhello");
    EXPECT_EQ_PTR(strpbrk(one, "\t\n\v"), one);
    EXPECT_EQ_PTR(strpbrk(one, "h"), one + 3);
    strcpy(one, "prefixsuffix");
    EXPECT_EQ_PTR(strpbrk(one, "s"), one + 6);
    EXPECT_EQ_PTR(strpbrk(one, "pre"), one);
    EXPECT_EQ_PTR(strpbrk(one, "fix"), one + 3);
    strcpy(one, "ABC");
    EXPECT_EQ_PTR(strpbrk(one, "A"), one);
    EXPECT_EQ_PTR(strpbrk(one, "B"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "C"), one + 2);
    EXPECT_EQ_PTR(strpbrk(one, "BC"), one + 1);
    EXPECT_NULL(strpbrk(one, "abc"));
    strcpy(one, "0123456789");
    EXPECT_EQ_PTR(strpbrk(one, "5"), one + 5);
    EXPECT_EQ_PTR(strpbrk(one, "9"), one + 9);
    EXPECT_NULL(strpbrk(one, "a"));
    strcpy(one, "abcdefghijklmnopqrstuvwxyz");
    EXPECT_EQ_PTR(strpbrk(one, "a"), one);
    EXPECT_EQ_PTR(strpbrk(one, "m"), one + 12);
    EXPECT_EQ_PTR(strpbrk(one, "z"), one + 25);
    EXPECT_NULL(strpbrk(one, "0123456789"));
    strcpy(one, "hello,world");
    EXPECT_EQ_PTR(strpbrk(one, ","), one + 5);
    EXPECT_EQ_PTR(strpbrk(one, ",."), one + 5);
    strcpy(one, "path/to/file");
    EXPECT_EQ_PTR(strpbrk(one, "/"), one + 4);
    EXPECT_EQ_PTR(strpbrk(one, "/\\"), one + 4);
    strcpy(one, "test123");
    EXPECT_EQ_PTR(strpbrk(one, "123"), one + 4);
    strcpy(one, "123test");
    EXPECT_EQ_PTR(strpbrk(one, "test"), one + 3);
    strcpy(one, "mississippi");
    EXPECT_EQ_PTR(strpbrk(one, "i"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "s"), one + 2);
    EXPECT_EQ_PTR(strpbrk(one, "p"), one + 8);
    strcpy(one, "programming");
    EXPECT_EQ_PTR(strpbrk(one, "gram"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "ing"), one + 3);
    strcpy(one, "a1b2c3");
    EXPECT_EQ_PTR(strpbrk(one, "123"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "abc"), one);
    strcpy(one, "!!!");
    EXPECT_EQ_PTR(strpbrk(one, "!"), one);
    EXPECT_NULL(strpbrk(one, "@"));
    strcpy(one, "a\203b");
    EXPECT_EQ_PTR(strpbrk(one, "\203"), one + 1);
    EXPECT_EQ_PTR(strpbrk(one, "b\203"), one + 1);
}
