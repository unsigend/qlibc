#include <limits.h>
#include <stdlib.h>
#include <utest.h>

UTEST_CASE(llabs)
{
    EXPECT_EQ_INT(llabs(0LL), 0LL);
    EXPECT_EQ_INT(llabs(1LL), 1LL);
    EXPECT_EQ_INT(llabs(-1LL), 1LL);
    EXPECT_EQ_INT(llabs(123LL), 123LL);
    EXPECT_EQ_INT(llabs(-123LL), 123LL);
    EXPECT_EQ_INT(llabs(456789LL), 456789LL);
    EXPECT_EQ_INT(llabs(-456789LL), 456789LL);
    EXPECT_EQ_INT(llabs(1000LL), 1000LL);
    EXPECT_EQ_INT(llabs(-1000LL), 1000LL);
    EXPECT_EQ_INT(llabs(32767LL), 32767LL);
    EXPECT_EQ_INT(llabs(-32767LL), 32767LL);
    EXPECT_EQ_INT(llabs(2147483647LL), 2147483647LL);
    EXPECT_EQ_INT(llabs(-2147483647LL), 2147483647LL);
    EXPECT_EQ_INT(llabs(LLONG_MAX), LLONG_MAX);
    EXPECT_EQ_INT(llabs(-LLONG_MAX), LLONG_MAX);
    EXPECT_EQ_INT(llabs(42LL), 42LL);
    EXPECT_EQ_INT(llabs(-42LL), 42LL);
    EXPECT_EQ_INT(llabs(999LL), 999LL);
    EXPECT_EQ_INT(llabs(-999LL), 999LL);
    EXPECT_EQ_INT(llabs(2000000000LL), 2000000000LL);
    EXPECT_EQ_INT(llabs(-2000000000LL), 2000000000LL);
    EXPECT_EQ_INT(llabs(9000000000LL), 9000000000LL);
    EXPECT_EQ_INT(llabs(-9000000000LL), 9000000000LL);
    EXPECT_EQ_INT(llabs(5000000000000LL), 5000000000000LL);
    EXPECT_EQ_INT(llabs(-5000000000000LL), 5000000000000LL);
    EXPECT_EQ_INT(llabs(9000000000000000000LL), 9000000000000000000LL);
    EXPECT_EQ_INT(llabs(-9000000000000000000LL), 9000000000000000000LL);
}
